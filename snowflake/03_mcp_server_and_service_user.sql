-- =============================================================================
-- Lab 18: Snowflake-Managed MCP Server + Least-Privilege Service User & IP Policy
-- SECURITY: Network policy is attached ONLY to SVC_LAB18_MCP, NEVER to ACCOUNT
--           or your admin human user.
-- =============================================================================

USE ROLE ACCOUNTADMIN;
USE DATABASE CRM_OSSIE_LAB18;
USE SCHEMA SEMANTIC;

-- 1. Snowflake-Managed MCP Server exposing Cortex Analyst over the Ossie Semantic View
CREATE OR REPLACE MCP SERVER CRM_OSSIE_LAB18.SEMANTIC.CRM_OSSIE_MCP_SERVER
FROM SPECIFICATION $$
tools:
  - name: "crm_account_analyst"
    type: "CORTEX_ANALYST_MESSAGE"
    identifier: "CRM_OSSIE_LAB18.SEMANTIC.CRM_ACCOUNT_SEMANTIC_VIEW"
    description: "Natural-language Cortex Analyst tool backed by the Apache Ossie CRM_ACCOUNT_SEMANTIC_VIEW over live Dataverse CRM accounts."
    title: "CRM Account Semantic Analyst"
$$;

-- 2. Least-privilege role for MCP client access
CREATE ROLE IF NOT EXISTS ROLE_LAB18_MCP;

GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE ROLE_LAB18_MCP;
GRANT USAGE ON DATABASE CRM_OSSIE_LAB18 TO ROLE ROLE_LAB18_MCP;
GRANT USAGE ON SCHEMA CRM_OSSIE_LAB18.SEMANTIC TO ROLE ROLE_LAB18_MCP;
GRANT USAGE ON MCP SERVER CRM_OSSIE_LAB18.SEMANTIC.CRM_OSSIE_MCP_SERVER TO ROLE ROLE_LAB18_MCP;

-- Read-only access to upstream CRM_LAB16 Bronze accounts + Lab 18 Dataverse lookup dims
GRANT USAGE ON DATABASE CRM_LAB16 TO ROLE ROLE_LAB18_MCP;
GRANT USAGE ON SCHEMA CRM_LAB16.CRM_BRONZE TO ROLE ROLE_LAB18_MCP;
GRANT SELECT ON TABLE CRM_LAB16.CRM_BRONZE.RAW_ACCOUNTS TO ROLE ROLE_LAB18_MCP;
GRANT SELECT ON TABLE CRM_OSSIE_LAB18.SEMANTIC.DIM_ACCOUNT_CATEGORY TO ROLE ROLE_LAB18_MCP;
GRANT SELECT ON TABLE CRM_OSSIE_LAB18.SEMANTIC.DIM_ACCOUNT_STATE TO ROLE ROLE_LAB18_MCP;

-- Semantic View & Cortex Analyst permissions
GRANT SELECT, REFERENCES ON SEMANTIC VIEW CRM_OSSIE_LAB18.SEMANTIC.CRM_ACCOUNT_SEMANTIC_VIEW TO ROLE ROLE_LAB18_MCP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_ANALYST_USER TO ROLE ROLE_LAB18_MCP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ROLE_LAB18_MCP;

-- 3. Scoped Network Policy (Workstation /32 IP ONLY) + Service User
CREATE NETWORK POLICY IF NOT EXISTS LAB18_WORKSTATION_IP_POLICY
    ALLOWED_IP_LIST = ('__ALLOWED_IP_CIDR__')
    COMMENT = 'Lab 18 scoped /32 egress policy for SVC_LAB18_MCP PAT auth only';

CREATE USER IF NOT EXISTS SVC_LAB18_MCP
    TYPE = SERVICE
    DEFAULT_ROLE = ROLE_LAB18_MCP
    DEFAULT_WAREHOUSE = SNOWFLAKE_LEARNING_WH
    COMMENT = 'Lab 18 least-privilege service user for HTTP Snowflake-Managed MCP';

ALTER USER SVC_LAB18_MCP SET
    DEFAULT_ROLE = ROLE_LAB18_MCP
    DEFAULT_WAREHOUSE = SNOWFLAKE_LEARNING_WH
    NETWORK_POLICY = LAB18_WORKSTATION_IP_POLICY;

GRANT ROLE ROLE_LAB18_MCP TO USER SVC_LAB18_MCP;
